#!/usr/bin/env node
/* Generate the browser's inert product catalog from the canonical JSON. */
'use strict';
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..'),file=path.join(root,'web/product_settings.js');
const settings=JSON.parse(fs.readFileSync(path.join(root,'product_settings.json'),'utf8'));
if(settings.schema!=='hrs-product-settings-v1')throw Error('Unknown product settings schema');
const source='/* Generated by tools/build_settings.js from product_settings.json; DO NOT edit. */\n'+
 '(function(root){\n\'use strict\';\nconst data='+JSON.stringify(settings,null,2)+';\n'+
 'function freeze(value){if(value&&typeof value===\'object\'){Object.values(value).forEach(freeze);Object.freeze(value);}return value;}\n'+
 'root.ReportSettings=freeze(data);if(typeof module!==\'undefined\'&&module.exports)module.exports=root.ReportSettings;\n'+
 '})(typeof window!==\'undefined\'?window:globalThis);\n';
if(process.argv.includes('--write'))fs.writeFileSync(file,source);
else if(!fs.existsSync(file)||fs.readFileSync(file,'utf8')!==source){console.error('Browser settings differ; run node app/tools/build_settings.js --write');process.exitCode=1;}
else console.log('Product settings generated browser catalog PASS');
const paths=JSON.parse(fs.readFileSync(path.join(root,'asset_paths.json'),'utf8'));
if(paths.schema!=='hrs-asset-paths-v1')throw Error('Unknown asset paths schema');
const assetFile=path.join(root,'web/asset_paths_data.js');
const assetSource='/* Generated from asset_paths.json by tools/build_settings.js; DO NOT edit. */\n'+
 '(function(root){const data='+JSON.stringify(paths,null,2)+';root.ReportAssetPathRules=data;'+
 'if(typeof module!=="undefined"&&module.exports)module.exports=data;})(typeof window==="undefined"?globalThis:window);\n';
if(process.argv.includes('--write'))fs.writeFileSync(assetFile,assetSource);
else if(!fs.existsSync(assetFile)||fs.readFileSync(assetFile,'utf8')!==assetSource){console.error('Asset rules differ; run node app/tools/build_settings.js --write');process.exitCode=1;}
else console.log('Asset paths generated browser catalog PASS');
